/**
 * src/lib/utils/markdown-normalizer.ts
 * 
 * LLM이 생성하거나 템플릿에서 병합된 마크다운에서 줄바꿈(\n)이 누락되어
 * 한 줄로 이어붙은 뷸렛, 번호 목록, 이모지 헤더, 테이블 행을 깔끔하게 개행 분리합니다.
 */

export function normalizeSectionMarkdown(content: string): string {
  if (!content) return '';
  let md = content;

  // 1. 인라인 볼드 이모지 헤더 분리: "자산입니다. **🚇 교통..." -> "자산입니다.\n\n**🚇 교통..."
  md = md.replace(/([^\n])\s+(\*\*[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE00}-\u{FE0F}][^*]+\*\*)/gu, '$1\n\n$2');
  // (Wave 9 Rule 1b 제거: "**양평** 소재…" 같은 문장 내 볼드 명사를 헤더로 오분리하는 회귀 발생)

  // 2. 인라인 볼드 헤더 뒤의 세부항목 분리: "**🚇 교통 및 도로 접근성** - 🚇" -> "**🚇 교통 및 도로 접근성**\n\n- 🚇"
  md = md.replace(/(\*\*[^*]+\*\*)\s*-\s+([\u{1F300}-\u{1FAFF}])/gu, '$1\n\n- $2');
  md = md.replace(/(\*\*[^*]+\*\*)\s*-\s+([가-힣A-Za-z])/gu, '$1\n\n- $2');

  // 3. 인라인 번호 목록 분리: "연락 2. **NDA 체결**" -> "연락\n\n2. **NDA 체결**"
  md = md.replace(/([^\n0-9])\s+(\d+\.\s+\*\*)/gu, '$1\n\n$2');

  // 4. 인라인 불릿 항목 분리: "분석합니다. • **원금" / "접근성 • 2018년" -> 개행 분리
  md = md.replace(/([^\n])\s+(•\s+(?:\*\*|[0-9가-힣A-Za-z\u{1F300}-\u{1FAFF}]))/gu, '$1\n\n$2');
  //    "·"는 한국어 가운뎃점("분석 · 연면적 기준", "주차 · 승강기")으로도 쓰이므로 문장부호 뒤에서만 불릿으로 간주
  md = md.replace(/([.?!。:])\s+(·\s+(?:\*\*|[0-9가-힣A-Za-z\u{1F300}-\u{1FAFF}]))/gu, '$1\n\n$2');
  // 4b. 인라인 대시 불릿 분리: "결과입니다. - 핵심 입지" / "현황. - 100% 공실" -> 개행 분리
  md = md.replace(/([.?!。])\s+(-\s+(?:\*\*|[0-9가-힣A-Za-z\u{1F300}-\u{1FAFF}]))/gu, '$1\n\n$2');

  // T1. 문장 끝에 붙은 표 헤더 분리: "자산입니다. | 항목 | 내용 |\n|---|" -> "자산입니다.\n\n| 항목 | 내용 |\n|---|"
  //     (줄 시작~표 사이에 파이프가 없고, 다음 줄이 구분선 행일 때만 — 표 내부 행 분할 방지)
  md = md.replace(/^([^\n|]*[^\n|\s])[ \t]+(\|[^\n]*\|[ \t]*\n[ \t]*\|[ \t:|-]+\|)/gm, '$1\n\n$2');
  // T2. 표 마지막 행 뒤에 붙은 인용구 분리: "| 250억 | > 본 매물은…" -> "| 250억 |\n\n> 본 매물은…"
  md = md.replace(/(\|)[ \t]+(>[ \t][^\n|]*)$/gm, '$1\n\n$2');
  // H1. 문장 끝 뒤에 붙어 줄을 끝맺는 볼드 소제목 분리: "있습니다. **권역 시세 벤치마킹**\n" -> "있습니다.\n\n**권역 시세 벤치마킹**\n"
  md = md.replace(/([.?!。])[ \t]+(\*\*[^*\n]{2,60}\*\*)[ \t]*$/gm, '$1\n\n$2');
  // Q1. 문장 끝 뒤에 붙은 인용구 분리: "기대됩니다. > **자산 하이라이트**:" -> "기대됩니다.\n\n> **자산 하이라이트**:"
  md = md.replace(/([.?!。])[ \t]+(>[ \t])/g, '$1\n\n$2');
  // T3. 표 마지막 행 뒤에 붙어 줄을 끝맺는 볼드 소제목 분리 (다음 표의 제목):
  //     "| 10F | … | 미정 | **임대차 종합 요약**\n| 구분 |" -> "| 10F | … | 미정 |\n\n**임대차 종합 요약**\n| 구분 |"
  md = md.replace(/^(\|[^\n]*\|)[ \t]+(\*\*[^*\n]+\*\*[:：]?)[ \t]*$/gm, '$1\n\n$2');
  // H2. 줄 머리의 짧은 볼드 라벨 + 볼드 문장 분리: "**자산 개요** **핵심 한줄 정의: …**" -> "**자산 개요**\n\n**핵심 한줄 정의: …**"
  //     (라벨에 숫자/콜론 없음, 조사로 끝나지 않음, 뒤 볼드는 10자 이상 문장일 때만 — "**양평** 소재" 류 오분리 방지)
  md = md.replace(/^(\*\*[^*\n\d:：]{1,19}[^*\n\d:：은는이가을를의에로와과도만]\*\*)[ \t]+(?=\*\*[^*\n]{10,}\*\*)/gm, '$1\n\n');

  // 5. 이미 줄바꿈이 있는 리스트 항목이나 헤더 앞에 빈 줄 삽입 (마크다운 렌더링 보장)
  // 단, 번호 목록 직후(예: "1.\n**")나 테이블 내부(|)는 제외
  md = md.replace(/([^\n0-9.])\n(?=[-*•·] |\d+[.)]\s|\*\*[\u{1F300}-\u{1FAFF}])/gmu, '$1\n\n');

  // 6. 만약 "1.\n\n**" 형태로 잘못 쪼개진 경우 "1. **"로 복원
  md = md.replace(/(\d+\.)\s*\n+\s*(\*\*)/gu, '$1 $2');

  // 7. 테이블 내부 파이프 뒤에 잘못 들어간 개행 제거: "|\n\n**항목** |" -> "| **항목** |"
  //    (Wave 9.2: 같은 줄에 파이프가 이어지는 셀 조각일 때만 — 독립된 볼드 소제목 줄을 표 행에 재접착하지 않음)
  md = md.replace(/(\|)[ \t]*\n+[ \t]*(\*\*)(?=[^\n]*\|)/gu, '$1 $2');

  // 8. 3개 이상의 연속 개행은 2개로 압축
  md = md.replace(/\n{3,}/g, '\n\n');

  return md.trim();
}
