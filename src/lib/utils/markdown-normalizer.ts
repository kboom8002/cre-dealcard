/**
 * src/lib/utils/markdown-normalizer.ts
 * 
 * LLM이 생성하거나 템플릿에서 병합된 마크다운에서 줄바꿈(\n)이 누락되어
 * 한 줄로 이어붙은 뷸렛, 번호 목록, 이모지 헤더, 테이블 행을 깔끔하게 개행 분리합니다.
 */

export function normalizeSectionMarkdown(content: string): string {
  if (!content) return '';
  let md = content;

  // 1. 인라인 볼드 이모지 헤더 분리: "자산입니다. **🚇 교통..." -> "자산입니다.\n\n**🚇 교통..."
  md = md.replace(/([^\n])\s+(\*\*[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE00}-\u{FE0F}][^*]+\*\*)/gu, '$1\n\n$2');

  // 2. 인라인 볼드 헤더 뒤의 세부항목 분리: "**🚇 교통 및 도로 접근성** - 🚇" -> "**🚇 교통 및 도로 접근성**\n\n- 🚇"
  md = md.replace(/(\*\*[^*]+\*\*)\s*-\s+([\u{1F300}-\u{1FAFF}])/gu, '$1\n\n- $2');
  md = md.replace(/(\*\*[^*]+\*\*)\s*-\s+([가-힣A-Za-z])/gu, '$1\n\n- $2');

  // 3. 인라인 번호 목록 분리: "연락 2. **NDA 체결**" -> "연락\n\n2. **NDA 체결**"
  md = md.replace(/([^\n0-9])\s+(\d+\.\s+\*\*)/gu, '$1\n\n$2');

  // 4. 인라인 불릿 항목 분리: "분석합니다. • **원금" -> "분석합니다.\n\n• **원금"
  md = md.replace(/([^\n])\s+([•·]\s+(?:\*\*|[가-힣A-Za-z\u{1F300}-\u{1FAFF}]))/gu, '$1\n\n$2');

  // 5. 이미 줄바꿈이 있는 리스트 항목이나 헤더 앞에 빈 줄 삽입 (마크다운 렌더링 보장)
  // 단, 번호 목록 직후(예: "1.\n**")나 테이블 내부(|)는 제외
  md = md.replace(/([^\n0-9.])\n(?=[-*•·] |\d+[.)]\s|\*\*[\u{1F300}-\u{1FAFF}])/gmu, '$1\n\n');

  // 6. 만약 "1.\n\n**" 형태로 잘못 쪼개진 경우 "1. **"로 복원
  md = md.replace(/(\d+\.)\s*\n+\s*(\*\*)/gu, '$1 $2');

  // 7. 테이블 내부 파이프 뒤에 잘못 들어간 개행 제거: "|\n\n**" -> "| **"
  md = md.replace(/(\|)\s*\n+\s*(\*\*)/gu, '$1 $2');

  // 8. 3개 이상의 연속 개행은 2개로 압축
  md = md.replace(/\n{3,}/g, '\n\n');

  return md.trim();
}
